def ts(sec: int) -> str:
    return f"{sec // 60:02d}:{sec % 60:02d}"


def dialog(cid, lang, first_q, bot_answer, ask_op, turns):
    """turns: [(сдвиг_сек_от_эскалации, speaker, text)] после эскалации (эскалация на 00:40)."""
    p = PRELUDE[lang]
    t = [(0, "client", first_q), (2, "bot", p[0]), (3, "bot", p[1]), (10, "bot", bot_answer),
         (30, "client", ask_op), (32, "bot", p[2]), (36, "client", p[5]), (37, "bot", p[3]), (40, "system", p[4])]
    t += [(40 + d, sp, tx) for d, sp, tx in turns]
    return {"conversation_id": cid, "channel": "agent chat", "language": lang, "audio_url": None,
            "transcript": [{"timestamp": ts(s), "speaker": sp, "text": tx} for s, sp, tx in t]}


D, GT = [], []


def add(d, gt, note):
    D.append(d)
    GT.append({"conversation_id": d["conversation_id"], "criteria": gt, "source": "synthetic", "note": note})


